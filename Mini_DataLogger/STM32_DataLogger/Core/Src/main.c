static void uart_log(const char *s){
	HAL_UART_Transmit(&huart1, (uint8_t *)s, (uint16_t)strlen(s), 1000);
}

static void flash_error(const char *stage, spif_err_t code) {
	char buf[96];
	snprintf (buf, sizeof(buf), "ERROR at %s: %d \r\n", stage, (int)code);
	uart_log(buf);
}

#define FLASH_TEST_WRITE 1

static void flash_test(void){
	spif_t flash = {0};
	spif_err_t err;

	char buf[128];
	const uint8_t tx[] = "Hello ESP32 from STM32";

	uint8_t rx[(sizeof(tx))] = {0};

	uart_log("\r\n---SPI FLASH TEST EMB 15 ---\r\n");

	err = spif_init(&flash, &hspi1, FLASH_CS_GPIO_Port, FLASH_CS_Pin);

	if (err!= SPIF_ERR_NONE) {
		flash_error ("spif_init", err);
		return;
	}

	snprintf (buf, sizeof(buf), "Maker ID:0x%02X, size: %lu bytes, sector: %lu bytes\r\n",
			(unsigned int)flash.manufacturer,
			(unsigned long)flash.size,
			(unsigned long)flash.sector_size);

	uart_log(buf);
	if (flash.sector_size == 0 || flash.size < flash.sector_size){
		uart_log ("ERROR:invalid geometry");
		return;
	}

	uint32_t sector = (uint32_t)(flash.size / flash.sector_size - 1U);
	uint32_t addr = SPIF_SECTOR_TO_ADDRESS (&flash, sector);

	snprintf (buf, sizeof(buf), "Text sector:%lu, address: 0x%08lX\r\n",
			(unsigned long)sector,
			(unsigned long)addr);
	uart_log (buf);

#if FLASH_TEST_WRITE

	uart_log ("Erasing... \r\n");
	err = spif_erase_sector(&flash, sector);
	if (err != SPIF_ERR_NONE){
		flash_error("erase", err);
		return;
	}

	uart_log("Writing...\r\n");
	err = spif_write (&flash, addr, tx, sizeof(tx));
	if (err != SPIF_ERR_NONE){
		flash_error("write", err);
		return;
	}

#endif

	uart_log("Reading...\r\n");
	err = spif_read (&flash, addr, rx, sizeof(rx));
	if (err != SPIF_ERR_NONE) {
		flash_error("read", err);
		return;
	}

	snprintf(buf, sizeof(buf), "Read:  %.*s\r\n",
			(int)(sizeof(rx)-1),
			(char*)rx);
	uart_log(buf);

	if (memcmp (tx,rx, sizeof(tx)) == 0){
		uart_log("FLASH TEST OK \r\n");
	} else {
		uart_log("FLASH TEST FAIL \r\n");
	}
}

